pub fn recognized(name: &str) -> bool {
    CORPUS_OPCODES.binary_search(&name).is_ok()
        || {
            let prefix = name.trim_end_matches(|c: char| c.is_ascii_digit());
            let suffix = &name[prefix.len()..];
            !suffix.is_empty()
                && suffix.parse::<u16>().is_ok_and(|n| n < 144)
                && CORPUS_OPCODES
                    .iter()
                    .any(|known| known.trim_end_matches(|c: char| c.is_ascii_digit()) == prefix)
        }
        || {
            // A macro can supply the controller number in a route spelling, so
            // the raw-source inventory cannot enumerate its expanded names.
            let prefix = name.trim_end_matches(|c: char| c.is_ascii_digit());
            let suffix = &name[prefix.len()..];
            suffix.parse::<u16>().is_ok_and(|n| n < 144)
                && ["_oncc", "_curvecc", "_smoothcc", "_stepcc"]
                    .iter()
                    .any(|marker| {
                        prefix.strip_suffix(marker).is_some_and(|base| {
                            CORPUS_OPCODES.binary_search(&base).is_ok()
                                && !["sample", "default_path"].contains(&base)
                        })
                    })
        }
        || ["on_locc", "on_hicc"].iter().any(|prefix| {
            name.strip_prefix(prefix)
                .and_then(|s| s.parse::<u16>().ok())
                .is_some_and(|n| n < 128)
        })
        || ["set_cc", "set_hdcc", "label_cc"].iter().any(|prefix| {
            name.strip_prefix(prefix)
                .and_then(|s| s.parse::<u16>().ok())
                .is_some_and(|n| n < 128)
        })
}
